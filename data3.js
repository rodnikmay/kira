/* ---------- углы: прямой, острый, тупой (зан. 25) ----------
   Угол рисуем по формуле, поэтому нарисованный угол всегда совпадает
   с правильным ответом: острый 35–55°, прямой ровно 90°, тупой 118–150°.
   Углы «из жизни» тоже рисуем сами (уголок тетради, ножницы, крыша домика). */
function bAngleRays(vx, vy, s1, s2, L, squareMark){
  /* дуга и отметка прямого угла видны в обеих темах: цвет не слишком тёмный и не слишком светлый */
  const col='#ff4d8d', dark='#d9557f', rad=d=>d*Math.PI/180;
  const x1=vx+L*Math.cos(rad(s1)), y1=vy+L*Math.sin(rad(s1));
  const x2=vx+L*Math.cos(rad(s2)), y2=vy+L*Math.sin(rad(s2));
  let out='<path d="M'+x1.toFixed(1)+','+y1.toFixed(1)+' L'+vx+','+vy+' L'+x2.toFixed(1)+','+y2.toFixed(1)+
          '" fill="none" stroke="'+col+'" stroke-width="7" stroke-linecap="round" stroke-linejoin="round"/>';
  if(squareMark){
    const r=26;
    const ax=vx+r*Math.cos(rad(s1)), ay=vy+r*Math.sin(rad(s1));
    const bx=vx+r*Math.cos(rad(s2)), by=vy+r*Math.sin(rad(s2));
    out+='<path d="M'+ax.toFixed(1)+','+ay.toFixed(1)+' L'+(ax+bx-vx).toFixed(1)+','+(ay+by-vy).toFixed(1)+
         ' L'+bx.toFixed(1)+','+by.toFixed(1)+'" fill="none" stroke="'+dark+'" stroke-width="3"/>';
  } else {
    const steps=20, r=Math.min(42,L*0.34); let pts='';
    for(let i=0;i<=steps;i++){ const a=s1+(s2-s1)*i/steps;
      pts+=(i?' ':'')+(vx+r*Math.cos(rad(a))).toFixed(1)+','+(vy+r*Math.sin(rad(a))).toFixed(1); }
    out+='<polyline points="'+pts+'" fill="none" stroke="'+dark+'" stroke-width="3"/>';
  }
  out+='<circle cx="'+vx+'" cy="'+vy+'" r="6.5" fill="'+dark+'"/>';
  return {svg:out, x1:x1, y1:y1, x2:x2, y2:y2};
}

function bAngleSvg(kind, s){
  const deg = kind==='прямой' ? 90 : (kind==='острый' ? 35+rnd(21) : 118+rnd(33));
  const L=118, vx=30, vy=116;
  const r=bAngleRays(vx, vy, 0, -deg, L, deg===90);
  const pad=18;
  const minX=Math.min(vx,r.x1,r.x2)-pad, maxX=Math.max(vx,r.x1,r.x2)+pad;
  const minY=Math.min(vy,r.y1,r.y2)-pad, maxY=vy+pad;
  const w=Math.round(maxX-minX), h=Math.round(maxY-minY);
  const outW=s||200;
  return '<svg viewBox="'+minX+' '+minY+' '+w+' '+h+'" width="'+outW+'" height="'+Math.round(outW*h/w)+'">'+r.svg+'</svg>';
}

