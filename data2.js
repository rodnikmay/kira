const SHAPE_GLYPH = {круг:'🔴', квадрат:'🟥', треугольник:'🔺', овал:'🥚', прямоугольник:'🟧'};
/* Для счёта фигурок берём только те формы, у которых значок однозначный,
   а «лишние» картинки — совсем других форм, чтобы счёт всегда совпадал с ответом. */
const COUNT_SHAPES = ['круг','квадрат','треугольник','овал'];
const COUNT_PLURAL = {круг:'круги', квадрат:'квадраты', треугольник:'треугольники', овал:'овалы'};
/* Значки «не считать»: только явно не-круглые и не-овальные формы.
   🌸 и 🍥 убраны — они округлые, и ребёнок засчитывает их как круг. */
const COUNT_OTHERS = ['⭐','❤️','🔶','🥕','➕','🏠'];
function makeCountShapes(){
  const target=pick(COUNT_SHAPES);
  const glyph=SHAPE_GLYPH[target];
  const others=COUNT_OTHERS.filter(g=>g!==glyph);
  const n=3+rnd(5);
  const row=pickN(others, 2+rnd(3)).map(g=>({g:g}));
  for(let i=0;i<n;i++) row.push({g:glyph});
  return {target:target, glyph:glyph, n:n, row:shuffle(row), plural:COUNT_PLURAL[target]};
}
